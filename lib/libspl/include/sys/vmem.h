#ifndef _SYS_VMEM_H
#define	_SYS_VMEM_H

#include <sys/kmem.h>

/*
 * In userspace there's (currently) no difference between an allocation from
 * a VM region and from a slab, so just route vmem_* through to kmem_*.
 */
#define	vmem_alloc(_s, _f)	kmem_alloc(_s, _f)
#define	vmem_zalloc(_s, _f)	kmem_zalloc(_s, _f)
#define	vmem_free(_b, _s)	kmem_free(_b, _s)

#endif
