# Usage:
#   make install 2>&1 | scripts/scan-install.pl
#
# The `make install` task generates a lot of output. This script is designed
# to filter out all the expected output messages, and just generate
# a summary of errors and warnings. Only exits non-zero if errors were actually
# generated.
#

use strict;
use warnings;

my @errors;
my @warnings;
my @relinks;
my %seen_warning;

while (<>) {
	chomp;

	# Collapse libtool relinking into one summary line later
	if (/^libtool:\s+warning:\s+relinking\s+'([^']+)'/) {
		push @relinks, $1;
		next;
	}

	# Module signing / SSL noise from unsigned kernels
	if (/^sign-file:/
	    || /SSL error:/
	    || /^At main\.c:/
	    || /^-\s+SSL error:/)
	{
		push @warnings, $_ unless $seen_warning{$_}++;
		next;
	}

	# all other warnings
	if (/[Ww]arning:/) {
		push @warnings, $_ unless $seen_warning{$_}++;
		next;
	}

	# Errors generated by linux/make, or freebsd/gmake
	if (/^(?:g?make)(?:\[\d+\])?: \*\*\*/
	    || /(?:^|:\s)(?:Permission denied|No space left on device)/
	    || /\bfatal error:/
	    || /^(?:libtool|collect2):\s+error:/)
	{
		push @errors, $_;
		next;
	}

	# Add other errors to catch here
	if (/\berror:/i || /\bFAILED\b/) {
		push @errors, $_;
		next;
	}
}

if (@relinks) {
	my %uniq;
	my @names = grep { !$uniq{$_}++ } @relinks;
	push @warnings, sprintf("libtool: warning: relinking %d libs: %s",
	    scalar @relinks, join(", ", @names));
}

if (!@errors && !@warnings) {
	exit 0;
}

if (@errors) {
	print "Errors (", scalar @errors, "):\n";
	print "  $_\n" for @errors;
}

if (@warnings) {
	if (@errors) {
		print "\n";
	}
	print "Warnings (", scalar @warnings, "):\n";
	print "  $_\n" for @warnings;
}

exit(@errors ? 1 : 0);
